LANGS = {
    "en": dict(idx=0, title="Tycho Survey", lang="en", cjk=None),
    "zh": dict(idx=1, title="Tycho 训练动力学巡天", lang="zh-CN", cjk=("Noto Sans SC", "Noto+Sans+SC")),
    "ja": dict(idx=2, title="Tycho 学習ダイナミクス観測", lang="ja", cjk=("Noto Sans JP", "Noto+Sans+JP")),
}


def build(code: str) -> Path:
    cfg = LANGS[code]
    i = cfg["idx"]
    s_style_end = TEMPLATE.index("</style>") + len("</style>")
    s_script = TEMPLATE.index("<script>")
    head, body, script = TEMPLATE[:s_style_end], TEMPLATE[s_style_end:s_script], TEMPLATE[s_script:]
    body = re.sub(r"\s+", " ", body)
    missing = []
    for row in sorted(BODY, key=lambda r: -len(r[0])):
        if row[0] not in body:
            missing.append(row[0][:70])
            continue
        if i:
            body = body.replace(row[0], row[i])
    for row in SCRIPT:
        if row[0] not in script:
            missing.append(row[0])
        elif i:
            script = script.replace(row[0], row[i])
    if missing:
        sys.exit("missing keys:\n  " + "\n  ".join(missing))
    head = head.replace("<title>Tycho Survey</title>", f"<title>{cfg['title']}</title>")
    if cfg["cjk"]:
        name, url = cfg["cjk"]
        head = head.replace("&display=swap\">", f"&family={url}:wght@400;500;700&display=swap\">", 1)
        for fam in ('"IBM Plex Sans Condensed", ', '"IBM Plex Sans", ', '"IBM Plex Mono", '):
            head = head.replace(fam, fam + f'"{name}", ', 1)
        body = body.replace('<div class="wrap">', f'<div class="wrap" lang="{cfg["lang"]}">', 1)
        if code == "zh":
            body = body.replace(">Refined information（棱镜）</text>", ">Refined information（棱镜）</text>")
    html = head + body + script.replace("__DATA__", json.dumps(DATA, separators=(",", ":")))
    name = "tycho-survey.html" if code == "en" else f"tycho-survey.{code}.html"
    path = OUT / name
    path.write_text(html)
    return path


